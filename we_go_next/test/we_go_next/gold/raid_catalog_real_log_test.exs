defmodule WeGoNext.Gold.RaidCatalogRealLogTest do
  use WeGoNext.DataCase, async: false

  import Ecto.Query

  alias WeGoNext.{CombatLogParser, Repo, Rules, Silver}
  alias WeGoNext.Gold.{DimEncounter, DimMechanicCriterion, DimPlayer, FactFailure}

  @fixtures Path.expand("../../fixtures", __DIR__)
  @expected @fixtures
            |> Path.join("raid_catalog_expected.json")
            |> File.read!()
            |> Jason.decode!()

  @moduledoc """
  Verbatim selected-event slices from /tmp/wgn-nif-090626.txt (September 6).
  Fixtures retain ENCOUNTER_START, COMBATANT_INFO, every player damage line for
  the authored avoidable IDs, and five lines per excluded damage ID as negative
  controls. Expected player/spell/pull hit counts and damage were independently
  counted with Python's CSV reader (amount after the 19-field advanced block),
  not generated by the NIF or projector under test.

  Source byte ranges: Nymrissa 5382296..66863953, Sszorak 132811535..161475803,
  Twin Fangs 385018445..443754659. These are filtered slices, not whole pulls.
  """

  for {id, boss, name, timestamp, expected_count} <- [
        {"435", "3379", "Nymrissa Wavecaller", "9/6/2026 11:03:00.375-4", 8},
        {"438", "3420", "Sszorak", "9/6/2026 11:27:31.796-4", 17},
        {"445", "3421", "The Twin Fangs", "9/6/2026 12:32:15.482-4", 14}
      ] do
    test "default sync builds exact player/spell facts for real #{name} pull #{id}" do
      encounter =
        %DimEncounter{}
        |> DimEncounter.changeset(%{
          source_encounter_key: "raid-catalog-#{unquote(id)}",
          wow_encounter_id: unquote(boss),
          name: unquote(name),
          difficulty_id: 15,
          difficulty_name: "Heroic",
          group_size: 23,
          instance_id: if(unquote(boss) == "3379", do: "2987", else: "3004")
        })
        |> Repo.insert!()

      path = Path.join(@fixtures, "raid_catalog_#{unquote(id)}.txt")

      assert {:ok, events} =
               CombatLogParser.parse_events(path, 0, File.stat!(path).size, unquote(timestamp))

      assert {:ok, _} = Silver.project_and_persist(encounter, events: events)

      assert {:ok, _} = Rules.sync_current_tier_rules(activate: true, promote: true)

      assert {:ok, %{inserted: unquote(expected_count)}} =
               FactFailure.rebuild_for_encounter(encounter.id)

      actual =
        from(f in FactFailure,
          join: p in DimPlayer,
          on: p.id == f.player_dim_id,
          join: c in DimMechanicCriterion,
          on: c.id == f.criterion_dim_id,
          where: f.encounter_dim_id == ^encounter.id,
          select: %{
            "guid" => p.player_guid,
            "spell" => c.spell_id,
            "hits" => f.failure_count,
            "damage" => f.total_damage
          }
        )
        |> Repo.all()
        |> Enum.sort_by(&{&1["guid"], &1["spell"]})

      expected = Enum.find(@expected, &(&1["id"] == unquote(id)))
      expected_rows = Enum.map(expected["rows"], &Map.take(&1, ~w(guid spell hits damage)))
      assert actual == expected_rows
      assert Enum.sum(Enum.map(actual, & &1["hits"])) == expected["hits"]

      # Repeated sync/rebuild must replace facts, not duplicate them.
      assert {:ok, _} = Rules.sync_current_tier_rules(activate: true, promote: true)

      assert {:ok, %{inserted: unquote(expected_count)}} =
               FactFailure.rebuild_for_encounter(encounter.id)

      assert Repo.aggregate(FactFailure, :count) == unquote(expected_count)
    end
  end
end
